#!/usr/bin/env bash
# scripts/ci/test-ship-no-checkout-mutation.sh — RESILIENT-1645 (PHASE-R R4/R1)
#
# PROVES, end-to-end against the real `chump` binary, that `chump gap ship`
# never moves or mutates the node checkout:
#
#   AC2  HEAD, the index and the working tree are byte-unchanged after a ship,
#        INCLUDING when origin/main is ahead of local main.
#   AC5  Cargo.lock and workspace-hack/Cargo.toml are byte-unchanged after a
#        ship — i.e. no `cargo build --release` (RESILIENT-492) and no
#        `cargo hakari generate` (RESILIENT-469) ran in the checkout.
#
# ship() reads origin/main through `git fetch` + rev-list/rev-parse ONLY; the
# proof-of-merge decision uses the fetched refs/remotes/origin/main, so the
# checkout stays put even though origin is ahead.
#
# Pure: real chump binary + git + sqlite3; no network (local bare origin).
#
# CI: wired in .github/workflows/ci.yml and crates/chump-preflight/src/preflight.rs.
set -uo pipefail

PASS=0; FAIL=0; FAILS=()
ok()   { printf '  PASS: %s\n' "$1"; PASS=$((PASS+1)); }
fail() { printf '  FAIL: %s\n' "$1"; FAIL=$((FAIL+1)); FAILS+=("$1"); }

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SRC="$REPO_ROOT/crates/chump-gap-store/src/lib.rs"

echo "=== RESILIENT-1645: gap ship must not mutate the node checkout ==="

# ── Source-level invariants: the two cargo calls are gone from the ship path ──
echo ""
echo "-- Source-level invariants (ship runs no cargo, no pull) --"

# Scope the grep to the ship() function body (through the finalize_status_done
# call) so a mention in an unrelated helper or doc comment doesn't false-fail.
ship_body="$(awk '/pub fn ship\(&self, gap_id: &str, session_id: &str, closed_pr: Option<i64>\) -> Result<\(\)> \{/{f=1} f{print} /DoneExtras::ShipCeremony,/{if(f)exit}' "$SRC")"

if grep -qE '"pull"|--ff-only' <<<"$ship_body"; then
    fail "ship() still contains a git pull / --ff-only (must be fetch-only)"
else
    ok "ship() contains no git pull / --ff-only"
fi

if grep -qE '"build", *"--release"|"hakari"' <<<"$ship_body"; then
    fail "ship() still invokes cargo build --release or cargo hakari (must be removed)"
else
    ok "ship() invokes no cargo build --release / cargo hakari"
fi

if grep -qE '"fetch", *"origin", *"main"' <<<"$ship_body"; then
    ok "ship() still fetches origin/main (fetch-only read of the merge target)"
else
    fail "ship() no longer fetches origin/main"
fi

# ── Binary end-to-end: origin ahead, checkout must not move ───────────────────
echo ""
echo "-- Binary end-to-end (origin/main ahead; checkout byte-unchanged) --"

CHUMP_BIN="${CHUMP_BIN:-}"
if [[ -z "$CHUMP_BIN" || ! -x "$CHUMP_BIN" ]]; then
    CHUMP_BIN="$REPO_ROOT/target/debug/chump"
fi
[[ -x "$CHUMP_BIN" ]] || CHUMP_BIN="$REPO_ROOT/target/release/chump"
[[ -x "$CHUMP_BIN" ]] || CHUMP_BIN="${HOME}/.cargo/bin/chump"

if [[ ! -x "$CHUMP_BIN" ]]; then
    echo "  SKIP: chump binary not found (run 'cargo build --bin chump' or set CHUMP_BIN)"
else
    TMP="$(mktemp -d -t test-resilient-1645.XXXXXX)"
    trap 'rm -rf "$TMP"' EXIT

    sha256() { sha256sum "$1" 2>/dev/null | awk '{print $1}'; }

    SHIP_REPO="$TMP/ship-repo"
    mkdir -p "$SHIP_REPO"
    git -C "$SHIP_REPO" init -q
    git -C "$SHIP_REPO" config user.email "test@integration.local"
    git -C "$SHIP_REPO" config user.name "Integration Test"
    git -C "$SHIP_REPO" checkout -q -b main

    # Synthetic workspace artifacts that the OLD code would have rewritten:
    # a cargo build would touch target/ and a hakari generate would rewrite
    # workspace-hack/Cargo.toml. Give them deterministic bytes and commit.
    printf 'name = "fixture"\n' > "$SHIP_REPO/Cargo.toml"
    printf '# fixture lockfile — must be byte-unchanged after ship\n' > "$SHIP_REPO/Cargo.lock"
    mkdir -p "$SHIP_REPO/workspace-hack"
    printf '# This file is generated by `cargo hakari`.\n[package]\nname = "workspace-hack"\n' \
        > "$SHIP_REPO/workspace-hack/Cargo.toml"
    git -C "$SHIP_REPO" add -A
    git -C "$SHIP_REPO" commit -q -m "chore: fixture workspace"

    # Bare origin in sync, then advance origin ONE commit carrying the gap ID.
    ORIGIN="$TMP/origin.git"
    git clone --bare -q "$SHIP_REPO" "$ORIGIN"
    git -C "$SHIP_REPO" remote add origin "$ORIGIN"
    git -C "$SHIP_REPO" push -q origin main

    export CHUMP_STATE_DB="$TMP/state.db"
    gap_id=$(
        FLEET_029_AMBIENT_GLANCE_SKIP=1 \
        "$CHUMP_BIN" gap reserve \
            --domain TEST \
            --title "TEST: RESILIENT-1645 no-checkout-mutation fixture" \
            --priority P3 --force 2>&1 | grep -E '^TEST-' | tail -1
    ) || true

    if [[ -z "$gap_id" ]]; then
        fail "could not reserve a test gap"
    else
        # Advance origin via a scratch clone with a commit carrying the gap ID.
        SCRATCH="$TMP/scratch"
        git clone -q "$ORIGIN" "$SCRATCH"
        git -C "$SCRATCH" config user.email "test@integration.local"
        git -C "$SCRATCH" config user.name "Integration Test"
        echo landed > "$SCRATCH/landed.txt"
        git -C "$SCRATCH" add landed.txt
        git -C "$SCRATCH" commit -q -m "feat(${gap_id}): landed on origin/main"
        git -C "$SCRATCH" push -q origin main

        # Snapshot the checkout BEFORE the ship.
        head_before=$(git -C "$SHIP_REPO" rev-parse HEAD)
        status_before=$(git -C "$SHIP_REPO" status --porcelain --untracked-files=no)
        lock_before=$(sha256 "$SHIP_REPO/Cargo.lock")
        hakari_before=$(sha256 "$SHIP_REPO/workspace-hack/Cargo.toml")
        index_before=$(git -C "$SHIP_REPO" rev-parse "$(git -C "$SHIP_REPO" write-tree)")

        SHIP_OUT=$(
            CHUMP_REPO="$SHIP_REPO" \
            CHUMP_SKIP_SUPERSEDED_CLOSE=1 \
            CHUMP_SHIP_NO_AUTOSTAGE=1 \
            CHUMP_ALLOW_STALE_DESTRUCTIVE=1 \
            CHUMP_GAP_SHIP_SKIP_STALE_CHECK=1 \
            "$CHUMP_BIN" gap ship "$gap_id" --closed-pr 9999 2>&1
        )
        SHIP_RC=$?

        [[ $SHIP_RC -eq 0 ]] \
            && ok "ship succeeded off the fetched origin/main (rc=0)" \
            || fail "ship exited $SHIP_RC; output: ${SHIP_OUT:0:200}"

        # origin was ahead — fetch must have happened but NOT a fast-forward.
        behind=$(git -C "$SHIP_REPO" rev-list --count main..origin/main 2>/dev/null || echo 0)
        [[ "$behind" == "1" ]] \
            && ok "local main still 1 behind origin (no fast-forward)" \
            || fail "local main is $behind behind origin — ship moved the checkout"

        [[ "$(git -C "$SHIP_REPO" rev-parse HEAD)" == "$head_before" ]] \
            && ok "HEAD byte-unchanged after ship" \
            || fail "HEAD moved after ship"

        index_after=$(git -C "$SHIP_REPO" rev-parse "$(git -C "$SHIP_REPO" write-tree)")
        [[ "$index_after" == "$index_before" ]] \
            && ok "index (tree) byte-unchanged after ship" \
            || fail "index changed after ship"

        [[ "$(git -C "$SHIP_REPO" status --porcelain --untracked-files=no)" == "$status_before" ]] \
            && ok "tracked working tree byte-unchanged after ship" \
            || fail "tracked working tree changed after ship"

        [[ "$(sha256 "$SHIP_REPO/Cargo.lock")" == "$lock_before" ]] \
            && ok "Cargo.lock byte-unchanged after ship (no cargo build)" \
            || fail "Cargo.lock changed after ship"

        [[ "$(sha256 "$SHIP_REPO/workspace-hack/Cargo.toml")" == "$hakari_before" ]] \
            && ok "workspace-hack/Cargo.toml byte-unchanged after ship (no hakari)" \
            || fail "workspace-hack/Cargo.toml changed after ship"

        [[ ! -e "$SHIP_REPO/build.log" ]] \
            && ok "no build.log created (no cargo build --release ran)" \
            || fail "build.log present — a cargo build ran in the checkout"
    fi
fi

echo ""
echo "=== Summary: $PASS passed, $FAIL failed ==="
if (( FAIL > 0 )); then
    for f in "${FAILS[@]}"; do printf '  - %s\n' "$f"; done
    exit 1
fi
echo "PASS"
